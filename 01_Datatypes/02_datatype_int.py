# ALL ABOUT INTEGERS and INTEGER OPERATIONS 
element = 10
print(f"value of element: {element}")
print(f"data type of element: {type(element)}") # int is a built-in data type in Python
print(f"data type of element: {id(10)}")
element = -20
print(f"value of element: {element}")
print(f"data type of element: {id(-20)}")  # Integers are immutable data types in Python
element = int(50.0)
print(f"value of element: {element}")
print(f"data type of element: {type(element)}") # type casting  

ele1=17
ele2=3
print(f"addition: {ele1} + {ele2} = {ele1+ele2}")
print(f"subtraction: {ele1} - {ele2} = {ele1-ele2}")
print(f"multiplication: {ele1} * {ele2} = {ele1*ele2}")
print(f"division: {ele1} / {ele2} = {ele1/ele2}") # always returns a float
print(f"floor division: {ele1} // {ele2} = {ele1//ele2}") # returns the quotient without the remainder
print(f"modulus: {ele1} % {ele2} = {ele1%ele2}") # returns the remainder
print(f"exponentiation: {ele1} ** {ele2} = {ele1**ele2}") # returns the result of ele1 raised to the power of ele2

