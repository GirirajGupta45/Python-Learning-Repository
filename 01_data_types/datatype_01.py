#BASICS OF DATA TYPES IN PYTHON

element=10
print(f"value of element: {element}")
print(f"data type of element: {type(element)}")
element=20.0
print(f"value of element: {element}")
print(f"data type of element: {type(element)}")  # loosely typed language

print(f"value of element: {id(10)}")  # immutable data type
print(f"value of element: {id(20.0)}")
